"""Regenerate report tables/plot coordinates from accepted, immutable result JSONs.

Run from any directory with Python 3. No EDA tools, SSH or third-party packages needed.
"""
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
BASE = "9141dfe3303d60b2f00747811eee80cb16db7269"
SOURCES = [
    "docs/ppa/primary-20261021-v2.json",
    "docs/ppa/algorithm2-n4-20261021.json",
    "docs/ppa/power-20261021.json",
    "docs/ppa/power-supplement-20261021.json",
    "docs/ppa/formality-20261021.json",
    "syn/profiles/saed32-rvt-tt-25ns-forqa-cap075-v2.json",
]
EXPECTED_CANONICAL_SHA256 = [
    "ce4a5e579e7ee4ea95c709e50f5b202c5fe14294f3f51f3dfa82df7d5bca326c",
    "f2880c1a6108339ba90b1c4593eadc42bbf9034e31e05b1e93c87368cf1334ce",
    "4cea4e7ed87d3989bebda6713e8425a397e6be8da3ef74d188facb9fa90dae9b",
    "4fc27e1ecf33deeee29de8a05dc49effac33b36e325b02d0f2337d023859e9dd",
    "804038ab1a66795bd736a3299e6289a6fd395e6345951b3573c9ffe7e5b45e33",
    "6f4777f001fba4e80c28ebda22bd071bc316d6ff3b2b267ff688145d8aa9774d",
]


def load(name):
    return json.loads((ROOT / name).read_text(encoding="utf-8"))


def main():
    inputs = list(map(load, SOURCES))
    canonical = [hashlib.sha256(json.dumps(d, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode()).hexdigest() for d in inputs]
    if canonical != EXPECTED_CANONICAL_SHA256:
        raise ValueError("Frozen evidence changed; review the manuscript and evidence before regenerating.")
    primary, supplement, cold, power, formal, profile = inputs
    cases = primary["cases"]
    keys = [(c["N"], c["policy"]) for c in cases]
    policies = ["fcfs", "rr", "fai-main"]
    assert len(keys) == len(set(keys)) == 9
    assert set(keys) == {(n, p) for n in [4, 8, 16] for p in policies}
    assert primary["setup_met_cases"] == primary["hold_met_cases"] == primary["electrical_met_cases"] == 9
    assert sum(c["coverage"]["untested"] for c in cases) == 140
    assert all(c["setup_slack_ns"] > 0 and c["hold_slack_ns"] > 0 for c in cases)
    assert all(c["D"] == 16 and c["M"] == 1 and c["descriptor_bits"] == 105 for c in cases)
    assert profile["clock"]["period"] == 25
    assert primary["profile_canonical_sha256"] == supplement["profile_canonical_sha256"] == cold["profile_canonical_sha256"] == power["profile_canonical_sha256"]
    assert len(formal["cases"]) == 14
    assert all(not any(c[k] for k in ["failing", "aborted", "unverified", "unmatched", "active_black_boxes"]) for c in formal["cases"])
    assert formal["negative_control"] == "INTENTIONAL_OUTPUT_INVERSION_DETECTED_ONE_POINT"
    assert len(cold["cases"]) == 9 and cold["total_checked_cycles"] == 900000
    assert len(power["cases"]) == 21 and power["total_checked_cycles"] == 32098500
    assert power["total_measured_cycles"] == 2100000

    names = {"fcfs": "FCFS", "rr": "RR", "fai-main": "Main"}
    out = ["% Generated by generate_results.py; edit accepted source data only through review."]

    def macro(name, text):
        out.append("\\newcommand{\\" + name + "}{" + text + "}")

    def rows(name, data):
        macro(name, "\n" + "\n".join(" & ".join(map(str, row)) + r" \\" for row in data) + "\n")

    rows("PrimaryRows", [
        [c["N"], names[c["policy"]], f'{c["cell_area"]/1000:.3f}',
         f'{int(c["sequential_cells"]):,}', f'{c["setup_slack_ns"]:.3f}', f'{c["hold_slack_ns"]:.3f}']
        for c in cases
    ])
    area = {(c["N"], c["policy"]): c for c in cases}
    deltas = []
    for n in [4, 8, 16]:
        m, f, r = (area[n, p] for p in ["fai-main", "fcfs", "rr"])
        deltas.append([n, f'{100*(m["cell_area"]/f["cell_area"]-1):.2f}',
                       f'{100*(m["cell_area"]/r["cell_area"]-1):.2f}',
                       *[f'{area[n,p]["area_partition"]["policy_subtree"]:.1f}' for p in policies]])
    rows("OverheadRows", deltas)
    for p, label in [("fcfs", "FCFS"), ("rr", "RR"), ("fai-main", "Main")]:
        macro("Area" + label, " ".join(f'({n},{area[n,p]["cell_area"]/1000:.9f})' for n in [4, 8, 16]))
        macro("Policy" + label, " ".join(f'({n},{area[n,p]["area_partition"]["policy_subtree"]/1000:.9f})' for n in [4, 8, 16]))
        macro("Setup" + label, " ".join(f'({n},{area[n,p]["setup_slack_ns"]:.9f})' for n in [4, 8, 16]))
    powers = {(509, c["n_src"], c["policy"]): c for c in cold["cases"]}
    for c in power["cases"]:
        if "cold-seed" in c["run_id"]:
            seed = 510 if "s510" in c["run_id"] else 511
            key = seed, c["n_src"], c["policy"]
            assert key not in powers
            powers[key] = c
    assert len(powers) == 27
    data = []
    for n in [4, 8, 16]:
        for p in policies:
            vals = [powers[s, n, p]["power"]["total_W"] * 1000 for s in [509, 510, 511]]
            assert all(v > 0 for v in vals)
            # Preserve the coarser precision actually printed by PT for N=16.
            fmt = ".1f" if n == 16 else ".3f"
            c = powers[509, n, p]
            energy = c["power"]["total_W"] * 0.0025 / c["fires"] * 1e12
            energy_text = f"{energy:.0f}" if n == 16 else f"{energy:.1f}"
            data.append([n, names[p], *[format(v, fmt) for v in vals], energy_text])
    rows("ColdPowerRows", data)
    for seed in [509, 510, 511]:
        for n in [4, 8, 16]:
            assert powers[seed,n,"rr"]["power"]["total_W"] < powers[seed,n,"fcfs"]["power"]["total_W"] < powers[seed,n,"fai-main"]["power"]["total_W"]
            assert len({powers[seed,n,p]["trace_sha256"] for p in policies}) == 1
    cold_plot = {}
    for n in [4, 8, 16]:
        for p in policies:
            # Plot only the precision printed by PrimeTime; N=16 is coarser.
            precision = 1 if n == 16 else 3
            cold_plot[n, p] = [round(powers[s, n, p]["power"]["total_W"] * 1000, precision) for s in [509, 510, 511]]
    for p, label in [("fcfs", "FCFS"), ("rr", "RR"), ("fai-main", "Main")]:
        macro("ColdMean" + label, " ".join(
            f'({n},{sum(cold_plot[n,p])/len(cold_plot[n,p]):.3f})' for n in [4, 8, 16]))
        seed_points = []
        for n in [4, 8, 16]:
            seed_points.extend(f'({n+dx:.2f},{value:.3f})' for dx, value in zip([-.24, 0, .24], cold_plot[n,p]))
        macro("ColdSeeds" + label, " ".join(seed_points))
    boundary = {c["policy"]: c for c in power["cases"] if "boundary" in c["run_id"]}
    assert set(boundary) == set(policies)
    assert all(c["accepted"] == 55109 and c["fires"] == 55108 for c in boundary.values())
    assert len({c["trace_sha256"] for c in boundary.values()}) == 1
    rows("BoundaryRows", [
        [names[p], f'{boundary[p]["power"]["internal_W"]*1000:.3f}',
         f'{boundary[p]["power"]["switching_W"]*1000:.5f}',
         f'{boundary[p]["power"]["leakage_W"]*1000:.3f}',
         f'{boundary[p]["power"]["total_W"]*1000:.3f}',
         f'{boundary[p]["power"]["total_W"]*.0025/55108*1e12:.1f}']
        for p in policies
    ])
    for field, macro_name, precision in [
        ("internal_W", "BoundaryInternal", 3),
        ("switching_W", "BoundarySwitching", 5),
        ("leakage_W", "BoundaryLeakage", 3),
    ]:
        macro(macro_name, " ".join(
            f'({i},{boundary[p]["power"][field]*1000:.{precision}f})'
            for i, p in enumerate(policies, start=1)))
    m, a = supplement["results"]
    assert m["policy"] == "fai-main" and a["policy"] == "fai-alg2"
    assert m["cell_area"] == area[4,"fai-main"]["cell_area"]
    assert a["sequential_cells"] == m["sequential_cells"] == 9011
    assert abs((a["cell_area"]/m["cell_area"]-1)*100 - supplement["total_area_relative_percent"]) < 1e-10
    rows("SupplementRows", [
        ["Total area (library units)", f'{m["cell_area"]:.3f}', f'{a["cell_area"]:.3f}'],
        ["Policy subtree area", f'{m["area_partition"]["policy_subtree"]:.3f}', f'{a["area_partition"]["policy_subtree"]:.3f}'],
        ["Flip-flop cells", "9,011", "9,011"],
        ["Setup slack (ns)", f'{m["setup_slack_ns"]:.6f}', f'{a["setup_slack_ns"]:.6f}'],
        ["Hold slack (ns)", f'{m["hold_slack_ns"]:.6f}', f'{a["hold_slack_ns"]:.6f}'],
        ["Constant-disabled checks", "68", "68"],
    ])
    directory = HERE / "generated"
    directory.mkdir(exist_ok=True)
    (directory / "results.tex").write_text("\n".join(out) + "\n", encoding="ascii")
    manifest = {
        "report_base_commit": BASE,
        "evidence_cutoff": "2026-10-21 Asia/Taipei",
        "scope": "Report-only; no new RTL, scheduler tests or remote EDA executions",
        "inputs": {name: hashlib.sha256((ROOT/name).read_bytes()).hexdigest() for name in SOURCES},
        "canonical_json_sha256": dict(zip(SOURCES, canonical)),
        "checks": {"primary_cases": 9, "cold_power_cases": 27, "boundary_power_cases": 3, "formality_pairs": 14,
                   "new_power_checked_cycles": 32098500, "new_power_measured_cycles": 2100000,
                   "energy_formula": "reported_total_W * measured_duration_seconds / measured_fires; includes leakage"},
        "generated_results_sha256": hashlib.sha256((directory/"results.tex").read_bytes()).hexdigest(),
    }
    (directory / "evidence_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print("PASS: accepted matrices, shared profile, positive slack, equivalence outcomes, traffic hashes, power ordering and derived tables/energy")
    print(directory / "results.tex")


if __name__ == "__main__":
    main()
